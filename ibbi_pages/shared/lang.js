function t(k) { return (T[LANG] && T[LANG][k] !== undefined) ? T[LANG][k] : (T.en[k] || k); }

function setLang(lang) {
  LANG = lang;
  localStorage.setItem('ibbi-lang', lang);
  const translations = T[lang];
  if (!translations) return;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[key] !== undefined) el.innerHTML = translations[key];
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  // Re-render active portal page so JS-rendered strings update
  if (typeof S !== 'undefined' && S.role) {
    if (document.getElementById('mob-root')) {
      // Mobile — re-render shell (bottomnav, sheet) then active page
      if (typeof renderMobShell === 'function') renderMobShell(S.role === 'business' ? 'biz' : 'infl');
      if (typeof mobNav === 'function') mobNav(S.role === 'business' ? (S.mobBizPage || 'dashboard') : (S.mobInflPage || 'dashboard'));
    } else {
      if (S.role === 'business' && typeof bizPage === 'function') {
        bizPage(S.bizPage || 'dashboard', true);
      } else if (S.role === 'influencer' && typeof inflPage === 'function') {
        inflPage(S.inflPage || 'dashboard', true);
      }
    }
  }
  // Re-render campaign wizard if open (appended to body, outside portal content)
  if (document.getElementById('create-camp-modal') && typeof _wizRefresh === 'function') {
    _wizRefresh();
  }
}

// Apply saved language on load
if (LANG !== 'en') {
  document.addEventListener('DOMContentLoaded', () => setLang(LANG));
  if (document.readyState !== 'loading') setLang(LANG);
}
